let elapsed = Date.now();
const MS_SEC = 1000;
const MS_MIN = 60 * MS_SEC;
const MS_HOUR = 60 * MS_MIN;
const MS_DAY = 24 * MS_HOUR;
const MS_MONTH = 30 * MS_DAY;
const MS_YEAR = 365 * MS_DAY;
const MS_DOOL = 10;

let rest = elapsed;
let years = Math.floor(rest / MS_YEAR);   rest = rest % MS_YEAR;
let months = Math.floor(rest / MS_MONTH); rest = rest % MS_MONTH;
let days = Math.floor(rest / MS_DAY);     rest = rest % MS_DAY;
let hours = Math.floor(rest / MS_HOUR);   rest = rest % MS_HOUR;
let minutes = Math.floor(rest / MS_MIN);  rest = rest % MS_MIN;
let seconds = Math.floor(rest / MS_SEC);  rest = rest % MS_SEC;
let dools = Math.floor(rest / MS_DOOL);   rest = rest % MS_DOOL;
let ms = rest;
